interface ToolIndex {
  exact: Map<string, KnownToolSpec>
  lower: Map<string, KnownToolSpec>
}

const INDEXES = new WeakMap<readonly KnownToolSpec[], ToolIndex>()

function indexOf(tools: readonly KnownToolSpec[]): ToolIndex {
  let idx = INDEXES.get(tools)
  if (!idx) {
    idx = { exact: new Map(), lower: new Map() }
    for (const spec of tools) {
      for (const name of spec.names) {
        if (!idx.exact.has(name)) idx.exact.set(name, spec)
        if (!idx.lower.has(name.toLowerCase())) idx.lower.set(name.toLowerCase(), spec)
      }
    }
    INDEXES.set(tools, idx)
  }
  return idx
}

/**
 * The spec for `program`: its basename (either slash) with a trailing `.exe` removed. Matching is
 * case-insensitive on win32 only.
 */
export function lookupTool(
  program: string,
  tools: readonly KnownToolSpec[] = KNOWN_TOOLS,
): KnownToolSpec | undefined {
  const base = (program.split(/[\\/]/).pop() ?? program).replace(/\.exe$/i, '')
  if (base === '') return undefined
  const idx = indexOf(tools)
  const hit = idx.exact.get(base)
  if (hit || process.platform !== 'win32') return hit
  return idx.lower.get(base.toLowerCase())
}
