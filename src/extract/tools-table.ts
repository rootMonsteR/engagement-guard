export type ToolCategory =
  | 'port-scanner'
  | 'web-scanner'
  | 'fuzzer'
  | 'passive-recon'
  | 'dns'
  | 'http-client'
  | 'remote-access'
  | 'smb-ad'
  | 'exploit-framework'
  | 'bruteforce'
  | 'dos'
  | 'fetch'
  | 'vcs'
  | 'package-manager'
  | 'interpreter'
  | 'listener'
  | 'inert'

/** Flags whose value embeds destinations in a tool-specific syntax (parsed by the extractor). */
export type EmbeddedForm =
  /** curl `--resolve host:port:addr[,addr]…`: each addr is contacted. */
  | 'curl-resolve'
  /** curl `--connect-to host1:port1:host2:port2`: host2:port2 is contacted. */
  | 'curl-connect-to'
  /** ssh `-L`/`-R` `[bind:]port:host:hostport`: host:hostport is a target, bind is infra. */
  | 'ssh-forward'
  /** ssh `-D [bind:]port`: the bind address is infra. */
  | 'ssh-dynamic'

/**
 * How the extractor reads one program's command line. Flags are listed exactly as the tool documents
 * them; `--name` and `-name` spellings of names longer than one letter are matched to each other
 * (not for `clusterShortFlags` tools, where `-name` is a cluster of switches).
 *
 * A flag takes a value when it appears in hostFlags, urlFlags, fileFlags, urlOrFileFlags,
 * excludeFlags, excludeFileFlags, infraFlags, nonTargetFlags, valueFlags, optionalValueFlags,
 * credentialHeaderFlags, embeddedFlags or rateFlags (unless the rate entry has an implied `value`);
 * every other listed flag is a switch, so a credential or override flag that takes a value is also
 * listed in one of the value lists.
 *
 * Roles of values (P16): host/url/file values are targets (role `target`); `infraFlags` values are
 * contacted but are infrastructure — resolvers, proxies, bind/source addresses (role `infra`);
 * `nonTargetFlags` values are never contacted (referer, user agent, request data, output files,
 * cookie values) and are left out of the literal sweep. Decoys, spoofed sources, idle-scan zombies
 * and FTP-bounce relays stay targets.
 */
export interface KnownToolSpec {
  names: string[]
  category: ToolCategory
  /** Default RoE tier of the action; `null` = not a network action (literals become inert). */
  tier: Tier | 'dos' | null
  /** Values are hosts/IPs/ranges (comma lists are split). */
  hostFlags?: string[]
  /** Values are URLs (or hosts). */
  urlFlags?: string[]
  /** Values are files with one target per line, read relative to the cwd. */
  fileFlags?: string[]
  /** A readable file is a target list; anything else is a target (katana `-u`/`-list`). */
  urlOrFileFlags?: string[]
  excludeFlags?: string[]
  excludeFileFlags?: string[]
  /** Values are contacted infrastructure (resolvers, proxies, bind addresses): role `infra`. */
  infraFlags?: string[]
  /** Values are never contacted and are not swept (referer, user agent, data, output, cookies). */
  nonTargetFlags?: string[]
  /** Flags whose value is not a target (skipped when looking for positionals; still swept). */
  valueFlags?: string[]
  /** Flags with an optional value: the next word is the value unless it starts with `-`. */
  optionalValueFlags?: string[]
  /** Value-taking flags whose value, when it names a file (a list), makes the action bruteforce. */
  bruteforceFileFlags?: string[]
  /** `-c key=value` style flags whose value is infrastructure when `key` matches (git http.proxy). */
  infraConfigFlags?: { flag: string; key: RegExp }[]
  /** Flags whose value embeds destinations (see `EmbeddedForm`). */
  embeddedFlags?: { flag: string; form: EmbeddedForm }[]
  /** Positional arguments are targets (default true). */
  positionalTargets?: boolean
  /** Only the first N positional arguments are targets (ssh destination, hydra server). */
  positionalLimit?: number
  /** Positional arguments matching this are skipped (dig record types, `+opts`, HTTP methods). */
  positionalSkip?: RegExp
  /** Only remote-looking positionals are targets: URLs and scp-style `[user@]host:path`. */
  remotePositionals?: boolean
  /** Option parsing stops at the first positional (OpenSSH: the rest is the remote command). */
  optionsEndAtFirstPositional?: boolean
  /** Words after `--` are this tool's command line (rustscan passes them to nmap). */
  afterDoubleDash?: string
  /** getopt-style clustering of single-letter flags (`-sSLo file`, `-lvnp 4444`). */
  clusterShortFlags?: boolean
  /**
   * e.g. `--version -V -h --help`: the segment does not touch the network. Only honoured at the top
   * level (before a subcommand, and before the first positional of a `positionalLimit` tool), and
   * never when the segment produced a flag, positional or file target.
   */
  nonNetworkFlags?: string[]
  /** nmap `--script brute` → bruteforce, `vuln` → intrusive, `dos` → dos. Highest matched tier wins. */
  tierOverrides?: { flag: string; value?: RegExp; tier: Tier | 'dos'; intrusive?: boolean }[]
  /** nmap `-iR`, hping3 `--flood`: refused outright. */
  hardDenyFlags?: { flag: string; reason: string }[]
  /** `value` is the implied value of a switch (hping3 `--fast` = `-i u10000`). */
  rateFlags?: { flag: string; kind: RateKind; value?: string }[]
  /** `-u user:pass`, `--password`, `-hashes`, cookie values: the action is credentialed. */
  credentialFlags?: string[]
  /** Header flags (`-H`) whose value is credentialed when it is an Authorization/API-key/Cookie header. */
  credentialHeaderFlags?: string[]
  /** Fields replaced (scalars) or merged (flag lists) after this first positional word. */
  subcommands?: Record<string, Partial<KnownToolSpec>>
  /**
   * Subcommands of a tier-`null` tool that never touch the network (`git status`): literals stay
   * inert. Any other subcommand that is not in `subcommands` is analysed like an unknown program.
   */
  localSubcommands?: string[]
}

